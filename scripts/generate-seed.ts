/**
 * Generates:
 *   supabase/seed.sql       — reference data (wilayas, communes, categories, products, ingredients, recipes)
 *   supabase/demo_seed.sql  — SYNTHETIC demo shops/observations, clearly marked as demo
 * from the TypeScript sources in src/data so the browser demo and the database never diverge.
 *
 * Usage: npm run seed:generate
 */
import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { CATEGORIES, INGREDIENTS, PRODUCTS } from '../src/data/reference/catalog';
import { RECIPES } from '../src/data/reference/recipes';
import { LOCAL_AREAS, WILAYAS } from '../src/data/reference/geography';
import { DEMO_SHOPS, demoObservationDefs } from '../src/data/demo/fixtures';
import { normalizeUnitPrice } from '../src/domain/units';
import { insert, jsonb, raw, textArray } from './sql';

const header = (title: string) =>
  `-- ${title}\n-- GENERATED by scripts/generate-seed.ts — do not edit by hand. Re-run \`npm run seed:generate\`.\n\n`;

let seed = header('As3ari reference data (no prices, no shops)');
seed += insert('public.wilayas', ['code', 'name_en', 'name_fr', 'name_ar', 'center_lat', 'center_lng', 'default_zoom', 'is_pilot'],
  WILAYAS.map((w) => [w.code, w.name_en, w.name_fr, w.name_ar, w.center_lat, w.center_lng, w.default_zoom, w.is_pilot]),
  '(code) do update set name_en = excluded.name_en, name_fr = excluded.name_fr, name_ar = excluded.name_ar, center_lat = excluded.center_lat, center_lng = excluded.center_lng, default_zoom = excluded.default_zoom, is_pilot = excluded.is_pilot');
seed += '\n' + insert('public.local_areas', ['id', 'wilaya_code', 'kind', 'name_en', 'name_fr', 'name_ar'],
  LOCAL_AREAS.map((a) => [a.id, a.wilaya_code, a.kind, a.name_en, a.name_fr, a.name_ar]));
seed += '\n' + insert('public.categories', ['id', 'name_en', 'name_fr', 'name_ar', 'recent_days', 'stale_days', 'sort_order'],
  CATEGORIES.map((c) => [c.id, c.name_en, c.name_fr, c.name_ar, c.recent_days, c.stale_days, c.sort_order]),
  '(id) do update set recent_days = excluded.recent_days, stale_days = excluded.stale_days, name_en = excluded.name_en, name_fr = excluded.name_fr, name_ar = excluded.name_ar, sort_order = excluded.sort_order');
seed += '\n' + insert('public.products',
  ['id', 'category_id', 'name_en', 'name_fr', 'name_ar', 'variant_en', 'variant_fr', 'variant_ar', 'dimension', 'search_terms', 'min_unit_price', 'max_unit_price'],
  PRODUCTS.map((p) => [p.id, p.category_id, p.name_en, p.name_fr, p.name_ar, p.variant_en, p.variant_fr, p.variant_ar, p.dimension, raw(textArray(p.search_terms)), raw(p.min_unit_price), raw(p.max_unit_price)]));
seed += '\n' + insert('public.ingredients', ['id', 'name_en', 'name_fr', 'name_ar', 'dimension', 'diet_tags', 'is_staple', 'pricing_product_id'],
  INGREDIENTS.map((i) => [i.id, i.name_en, i.name_fr, i.name_ar, i.dimension, raw(textArray(i.diet_tags)), i.is_staple, i.pricing_product_id]));
seed += '\n' + insert('public.recipes', ['id', 'name_en', 'name_fr', 'name_ar', 'servings', 'meal_slots', 'steps'],
  RECIPES.map((r) => [r.id, r.name_en, r.name_fr, r.name_ar, r.servings, raw(`array[${r.meal_slots.map((s) => `'${s}'`).join(', ')}]::public.meal_slot[]`), raw(jsonb(r.steps))]));
seed += '\n' + insert('public.recipe_ingredients', ['recipe_id', 'ingredient_id', 'quantity', 'unit'],
  RECIPES.flatMap((r) => r.ingredients.map((i) => [r.id, i.ingredient_id, raw(i.quantity), i.unit])));

let demo = header('SYNTHETIC DEMO DATA — not real shops, not real prices. Every row is marked demo.');
demo += '-- To remove all demo data:\n--   delete from public.price_reports where source = \'demo\';\n--   delete from public.shops where provenance = \'demo\';\n\n';
demo += insert('public.shops', ['id', 'name', 'kind', 'wilaya_code', 'area_id', 'address_text', 'lat', 'lng', 'provenance', 'provenance_note'],
  DEMO_SHOPS.map((s) => [s.id, s.name, s.kind, s.wilaya_code, s.area_id, s.address_text, s.lat, s.lng, 'demo', 'Synthetic location for demonstration only']));
const product = new Map(PRODUCTS.map((p) => [p.id, p]));
demo += '\n' + insert('public.price_reports',
  ['id', 'product_id', 'shop_id', 'contributor_id', 'price', 'quantity', 'unit', 'comparison_unit', 'normalized_price', 'observed_on', 'submitted_at', 'status', 'source', 'provenance_note'],
  demoObservationDefs().map((d) => {
    const n = normalizeUnitPrice(d.price, d.quantity, d.unit, product.get(d.product_id)!.dimension);
    if (!n.ok) throw new Error(`invalid demo row ${d.id}`);
    return [d.id, d.product_id, d.shop_id, null, raw(d.price), raw(d.quantity), d.unit, n.unit, raw(n.value),
      raw(`public.today_algeria() - ${d.days_ago}`), raw(`now() - interval '${d.days_ago} days'`), 'approved', 'demo', 'Synthetic demo value'];
  }));

writeFileSync(resolve('supabase/seed.sql'), seed);
writeFileSync(resolve('supabase/demo_seed.sql'), demo);
console.log(`seed.sql: ${PRODUCTS.length} products, ${RECIPES.length} recipes, ${WILAYAS.length} wilayas`);
console.log(`demo_seed.sql: ${DEMO_SHOPS.length} demo shops, ${demoObservationDefs().length} demo observations`);
