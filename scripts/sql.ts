/** Minimal SQL literal helpers for offline seed/import generation (output is reviewed, then run by the owner). */
export function lit(v: unknown): string {
  if (v === null || v === undefined) return 'null';
  if (typeof v === 'number') {
    if (!Number.isFinite(v)) throw new Error(`Non-finite number: ${v}`);
    return String(v);
  }
  if (typeof v === 'boolean') return v ? 'true' : 'false';
  if (typeof v === 'string') {
    if (v.includes('\u0000')) throw new Error('NUL byte in string');
    return `'${v.replace(/'/g, "''")}'`;
  }
  throw new Error(`Unsupported literal: ${typeof v}`);
}

export function textArray(values: string[]): string {
  return values.length ? `array[${values.map(lit).join(', ')}]::text[]` : `'{}'::text[]`;
}

export function jsonb(v: unknown): string {
  return `${lit(JSON.stringify(v))}::jsonb`;
}

export function insert(table: string, columns: string[], rows: unknown[][], conflict = 'do nothing'): string {
  if (!rows.length) return '';
  const values = rows.map((r) => `  (${r.map((c) => (typeof c === 'object' && c !== null && 'raw' in c ? (c as { raw: string }).raw : lit(c))).join(', ')})`);
  return `insert into ${table} (${columns.join(', ')}) values\n${values.join(',\n')}\non conflict ${conflict};\n`;
}

/** Mark a value as raw SQL (trusted, generated by our own code only). */
export const raw = (sql: string) => ({ raw: sql });
